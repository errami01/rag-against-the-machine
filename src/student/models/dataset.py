from typing import List

from pydantic import BaseModel, ConfigDict, Field


class MinimalSource(BaseModel):
    """A metadata reference pointing to a specific snippet within a source
      file.

    Tracks the raw file origin along with precise structural character
      offsets, allowing the system to locate the exact grounding context.

    Attributes:
        file_path: The filesystem or repository path of the source document.
        first_character_index: The starting 0-indexed character boundary.
        last_character_index: The ending 0-indexed character boundary.
    """
    file_path: str
    first_character_index: int
    last_character_index: int


class UnansweredQuestion(BaseModel):
    """Represents a base question submitted to the evaluation harness.

    Supports population via localized model field names or explicit JSON alias
    mappings frequently found in standard dataset files.

    Attributes:
        question_id: A unique identifier tied to the query instance.
        question: The actual text string of the query. Maps to 'question_str'
          during serialization/deserialization.
    """
    model_config = ConfigDict(populate_by_name=True)
    question_id: str
    question: str = Field(..., alias="question_str")


class AnsweredQuestion(UnansweredQuestion):
    """An extension of a basic question containing verified grounding data.

    Combines the baseline question identity with ground-truth reference texts
      and the target answer payload.

    Attributes:
        sources: A list of verified document snippets used to build the
          answer.
        answer: The expected gold-standard textual answer.
    """
    sources: List[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A root container parsing a collective evaluation batch.

    Handles mixed sequences containing polymorphic question definitions (both
    answered reference states and naked test queries).

    Attributes:
        rag_questions: An ordered collection of answered or unanswered question
          objects.
    """
    rag_questions: list[UnansweredQuestion | AnsweredQuestion]


class MinimalSearchResults(BaseModel):
    """Captured result profile showing retrieval performance for a single
      query.

    Maps out what text chunks the search infrastructure fetched in response
    to an input question.

    Attributes:
        question_id: The unique identifier of the evaluated query.
        question: The text string of the query. Maps to 'question_str'
          during processing.
            retrieved_sources: The set of candidate chunks isolated by the
              index.
    """
    model_config = ConfigDict(populate_by_name=True)
    question_id: str
    question: str = Field(..., alias="question_str")
    retrieved_sources: list[MinimalSource]


class StudentSearchResults(BaseModel):
    """Aggregated manifest containing a student submission's retrieval
      footprint.

    Tracks systemic search execution records alongside execution parameters
    across a complete dataset loop.

    Attributes:
        search_results: Batch collection of individual query-to-source
          mappings.
        k: The global maximum retrieval cutoff depth configured for the
          index run.
    """
    search_results: list[MinimalSearchResults]
    k: int


class MinimalAnswer(MinimalSearchResults):
    """An extension of a search result capturing generated response text.

    Pairs a set of candidate document chunks with a generated natural language
      solution.

    Attributes:
        answer: The final textual response generated by the language model.
    """
    answer: str


class StudentSearchResultsAndAnswer(StudentSearchResults):
    """The final completed submission model containing both retrieval maps and
      answers.

    This represents the full output payload generated by a student's RAG
      pipeline, ready to be evaluated by an automated scoring script.

    Attributes:
        search_results: Batch collection of answered queries accompanied by
          their retrieval histories.
    """
    search_results: List[MinimalAnswer]
